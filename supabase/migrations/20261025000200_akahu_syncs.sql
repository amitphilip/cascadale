-- One row per account per Akahu sync: the exact window asked for and what came back.
-- The next sync starts from the latest successful range_end (less a few days of overlap
-- for transactions the bank posts late), so it never re-reads an account's whole history.

create table akahu_syncs (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  account_id integer not null references accounts (id) on delete cascade,
  -- the Akahu account (acc_…) synced; a sync only resumes from runs of the same one
  akahu_account_id text not null,
  -- the window sent to Akahu: start exclusive (null = all history), end inclusive
  range_start timestamptz,
  range_end timestamptz not null,
  -- 'app' (Sync now or linking) or 'schedule' (the hourly cron job)
  run_by text not null,
  started_at timestamptz not null default now(),
  -- null while running; set with fetched/inserted on success, or with error on failure
  finished_at timestamptz,
  fetched integer,
  inserted integer,
  error text
);
create index akahu_syncs_account_idx on akahu_syncs (account_id, akahu_account_id, range_end desc);

alter table akahu_syncs enable row level security;
create policy "own rows" on akahu_syncs for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create index on akahu_syncs (user_id);
