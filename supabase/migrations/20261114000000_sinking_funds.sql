-- Sinking fund pots: a pot that money goes into on a schedule and lumpy, known costs are
-- paid out of (air tickets, invoices). It keeps a ledger of what went in and what was drawn,
-- with a running balance, an optional cap and an end date or a yearly reset. Transactions
-- drawn from one keep their category for reporting but leave its budget (lib/pots.ts).

alter table plan_pots
  add column type text not null default 'set_aside' check (type in ('set_aside', 'sinking_fund')),
  -- the most the fund pays out per cycle; null for no cap
  add column cap_amount numeric(14, 2) check (cap_amount is null or cap_amount > 0),
  -- the last day it runs; null for open-ended
  add column end_date date,
  -- a yearly reset on this date's day and month: totals and cap start again
  add column reset_date date,
  -- at a reset, the balance left over carries into the next cycle or is released
  add column reset_mode text not null default 'carry' check (reset_mode in ('carry', 'release')),
  -- scheduled contributions count from this date; earlier ones are frozen in pot_entries
  add column scheduled_from date;

create table pot_entries (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  pot_id integer not null references plan_pots (id) on delete cascade,
  -- contribution: money in (a top-up, or a scheduled one frozen when the schedule changed);
  -- draw: money out; planned_draw: an expected one-off still to come
  kind text not null check (kind in ('contribution', 'draw', 'planned_draw')),
  -- positive, as it moves the fund; a linked transaction's own amount wins when read
  amount numeric(14, 2) not null,
  date date not null,
  -- the transaction this is; deleting the transaction drops the link
  transaction_id integer references transactions (id) on delete cascade,
  note text,
  -- a scheduled contribution, frozen when the pot's schedule changed
  scheduled boolean not null default false,
  created_by text not null check (created_by in ('website', 'mcp', 'cas')),
  created_at timestamptz not null default now(),
  check (kind <> 'planned_draw' or transaction_id is null)
);
-- a transaction is drawn from (or paid into) one fund at most
create unique index pot_entries_transaction_idx on pot_entries (user_id, transaction_id)
  where transaction_id is not null;
create index pot_entries_pot_idx on pot_entries (pot_id, date);
create index on pot_entries (user_id);

alter table pot_entries enable row level security;
create policy "household rows" on pot_entries for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));

-- Transactions a live sinking fund pays for: they leave their category's budget.
create function pot_funded(p_transaction_id integer)
returns boolean
language sql stable as $$
  select exists (
    select 1
    from pot_entries e
    join plan_pots p on p.id = e.pot_id
    where e.transaction_id = p_transaction_id
      and e.kind = 'draw'
      and p.type = 'sinking_fund'
      and not p.removed
  )
$$;

create or replace function category_spend(p_start date, p_end date)
returns table (id integer, name text, budget numeric, spent numeric)
language sql stable as $$
  select c.id, c.name, c.monthly_budget, -sum(t.amount) as spent
  from transactions t
  left join categories c on c.id = t.category_id
  where t.date >= p_start and t.date < p_end
    and (c.kind = 'expense' or (c.id is null and t.amount < 0))
    and not pot_funded(t.id)
  group by c.id, c.name, c.monthly_budget
  order by spent desc
$$;

create or replace function category_spend_for(p_start date, p_end date, p_accounts integer[])
returns table (id integer, name text, budget numeric, spent numeric)
language sql stable as $$
  select c.id, c.name, c.monthly_budget, -sum(t.amount) as spent
  from transactions t
  left join categories c on c.id = t.category_id
  where t.date >= p_start and t.date < p_end
    and t.account_id = any (p_accounts)
    and (c.kind = 'expense' or (c.id is null and t.amount < 0))
    and not pot_funded(t.id)
  group by c.id, c.name, c.monthly_budget
  order by spent desc
$$;

-- The planner projects day-to-day spending from these, so a fund's draws stay out: the
-- simulation pays the fund's planned draws from the fund instead.
create or replace function plan_transactions(p_start date, p_end date)
returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(to_jsonb(x) order by x.date, x.id), '[]')
  from (
    select t.id, t.date::text as date, t.account_id as "accountId", t.description, t.amount,
      t.category_id as "categoryId", c.kind as "categoryKind",
      t.rule_id as "ruleId", r.note as "ruleNote"
    from transactions t
    left join categories c on c.id = t.category_id
    left join rules r on r.id = t.rule_id
    where t.date >= p_start and t.date < p_end
      and not pot_funded(t.id)
  ) x
$$;

-- Check-ins name the fund a transaction was drawn from, and leave it out of the categories.
create or replace function checkin_transactions(p_since timestamptz, p_recent_days integer)
returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(to_jsonb(x) - 'id' order by x.date, x.id), '[]')
  from (
    select t.id, t.date::text as date, t.description, t.amount, t.account_id as "accountId",
      c.name as "categoryName", c.kind as "categoryKind",
      (
        select p.name from pot_entries e join plan_pots p on p.id = e.pot_id
        where e.transaction_id = t.id and e.kind = 'draw'
          and p.type = 'sinking_fund' and not p.removed
        limit 1
      ) as pot
    from transactions t
    left join categories c on c.id = t.category_id
    where coalesce(c.kind, '') <> 'transfer'
      and case when p_since is not null then t.created_at > p_since
        else t.date > (select max(date) from transactions) - p_recent_days end
  ) x
$$;

revoke execute on function pot_funded(integer) from public, anon;
grant execute on function pot_funded(integer) to authenticated;
