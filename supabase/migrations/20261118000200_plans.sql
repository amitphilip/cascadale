-- The plan Cas makes: from projected income, the budgets you set, recurring bills and your
-- one-off payments, it says whether your goals are realistic and lays out where the money
-- goes (allocations) and what to do (actions). The newest plan is the current one; older
-- ones are kept as history. The old plan_* tables are no longer read.

create table plans (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  -- what you asked Cas to plan for, in your words
  goals text,
  summary text not null,
  verdict text not null check (verdict in ('realistic', 'stretch', 'unrealistic')),
  verdict_note text not null,
  -- each goal Cas weighed, and whether it fits: [{ goal, fits, note }]
  goal_checks jsonb not null default '[]',
  -- the monthly figures the plan was made from (income, committed, one-offs, left over)
  figures jsonb not null,
  -- website: you asked on the Plan page; mcp: Claude did, on your say-so
  made_by text not null default 'website' check (made_by in ('website', 'mcp')),
  created_at timestamptz not null default now()
);
create index on plans (user_id, id desc);

create table plan_items (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  plan_id integer not null references plans (id) on delete cascade,
  -- allocation: money set aside for something, on a schedule; action: something to do
  kind text not null check (kind in ('allocation', 'action')),
  -- for allocations: what the money is for
  purpose text check (purpose in ('bills', 'budget', 'one_off', 'savings', 'goal', 'buffer')),
  title text not null,
  detail text,
  amount numeric(14, 2) check (amount is null or amount >= 0),
  every text check (every in ('week', 'fortnight', 'month', 'once')),
  category_id integer references categories (id) on delete set null,
  one_off_id integer references one_offs (id) on delete set null,
  -- where the money should sit
  account_id integer references accounts (id) on delete set null,
  due_date date,
  done_at timestamptz,
  position integer not null default 0
);
create index on plan_items (plan_id, position);

alter table plans enable row level security;
create policy "household rows" on plans for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));

alter table plan_items enable row level security;
create policy "household rows" on plan_items for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));
