-- Plan instructions shared by the website and the MCP servers (lib/plan-service.ts):
-- pots you asked for, one-off adjustments on given dates, and a log of every change with
-- who made it (website, mcp or cas), when and why. A rebuild applies them to the plan.

create table plan_pots (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  name text not null,
  -- set aside each time it's funded
  amount numeric(14, 2) not null,
  frequency text not null check (frequency in ('payday', 'fortnightly', 'monthly')),
  -- null: the funding income's account
  from_account_id integer references accounts (id) on delete set null,
  -- null: earmarked in the from account
  to_account_id integer references accounts (id) on delete set null,
  -- the income that funds it: its recurring series key, and its name when set
  income_key text,
  income_name text,
  -- series keys of the bills it pays
  covers text[] not null default '{}',
  note text,
  -- a tombstone: take the pot out of the plan, even one the planner made
  removed boolean not null default false,
  updated_by text not null check (updated_by in ('website', 'mcp', 'cas')),
  updated_at timestamptz not null default now(),
  reason text
);
create unique index plan_pots_name_idx on plan_pots (user_id, lower(name));

create table plan_adjustments (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  date date not null,
  kind text not null check (kind in ('skip', 'add', 'change_amount')),
  target text not null check (target in ('bill', 'pot', 'transfer')),
  -- the bill's series key or the pot's name; null for a transfer
  ref text,
  name text not null,
  amount numeric(14, 2),
  from_account_id integer references accounts (id) on delete set null,
  to_account_id integer references accounts (id) on delete set null,
  created_by text not null check (created_by in ('website', 'mcp', 'cas')),
  created_at timestamptz not null default now(),
  reason text,
  -- removed adjustments are kept as history
  removed_at timestamptz,
  removed_by text check (removed_by in ('website', 'mcp', 'cas')),
  removed_reason text
);
create index plan_adjustments_date_idx on plan_adjustments (date);

-- One row per write. operation_id makes writes idempotent: the same id again returns the
-- stored result instead of changing anything twice.
create table plan_changes (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  operation_id text not null,
  actor text not null check (actor in ('website', 'mcp', 'cas')),
  action text not null,
  reason text,
  summary text,
  -- what the write returned; null while it's running
  result jsonb,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);
create unique index plan_changes_operation_idx on plan_changes (user_id, operation_id);
create index plan_changes_created_idx on plan_changes (created_at desc);

do $$
declare
  t text;
begin
  foreach t in array array['plan_pots', 'plan_adjustments', 'plan_changes'] loop
    execute format('alter table %I enable row level security', t);
    execute format(
      'create policy "household rows" on %I for all to authenticated '
      'using (user_id = (select public.data_owner())) '
      'with check (user_id = (select public.data_owner()))', t);
    execute format('create index on %I (user_id)', t);
  end loop;
end;
$$;

-- Who built each plan: null for the planner chat, else the actor that rebuilt it.
alter table plan_threads add column made_by text check (made_by in ('website', 'mcp', 'cas'));

-- Cas's decisions that change the plan, and the plan change that applied each one.
alter table cas_notes
  add column affects_plan boolean not null default false,
  add column applied_at timestamptz,
  add column applied_change_id integer references plan_changes (id) on delete set null;

-- Every transaction in [p_start, p_end), transfers included, with the rule that
-- categorized it. The planner pairs transfers between your accounts itself.
create function plan_transactions(p_start date, p_end date)
returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(to_jsonb(x) order by x.date, x.id), '[]')
  from (
    select t.id, t.date::text as date, t.account_id as "accountId", t.description, t.amount,
      t.category_id as "categoryId", c.kind as "categoryKind",
      t.rule_id as "ruleId", r.note as "ruleNote"
    from transactions t
    left join categories c on c.id = t.category_id
    left join rules r on r.id = t.rule_id
    where t.date >= p_start and t.date < p_end
  ) x
$$;
revoke execute on function plan_transactions(date, date) from public, anon;
grant execute on function plan_transactions(date, date) to authenticated;

-- Akahu only covers New Zealand banks: households without a currency or locale get NZD
-- and en-NZ rather than the app's old USD default.
insert into settings (user_id, key, value)
select distinct user_id, 'currency', 'NZD' from accounts
on conflict (user_id, key) do nothing;
insert into settings (user_id, key, value)
select distinct user_id, 'locale', 'en-NZ' from accounts
on conflict (user_id, key) do nothing;
