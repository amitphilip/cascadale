-- One-off payments: a known total, paid out in one go on a finish date or in parts until
-- it, with the money gathered in a tracking account first. Several one-offs can share an
-- account: each counts only the transactions linked to it, and lib/one-offs.ts works out
-- what to put in and when from what's left.

create table one_offs (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  name text not null,
  total numeric(14, 2) not null check (total > 0),
  -- the account the money is gathered in and paid out of
  account_id integer not null references accounts (id) on delete cascade,
  start_date date not null,
  finish_date date not null,
  -- single: paid in one go on the finish date; spread: in parts every out_every until it
  out_mode text not null default 'single' check (out_mode in ('single', 'spread')),
  out_every text check (out_every in ('week', 'fortnight', 'month')),
  -- how often money goes into the account for it, from the start date
  in_every text not null default 'month' check (in_every in ('week', 'fortnight', 'month')),
  -- already in the account for it when it was added
  set_aside numeric(14, 2) not null default 0 check (set_aside >= 0),
  note text,
  created_at timestamptz not null default now(),
  check (finish_date >= start_date),
  check (out_mode = 'single' or out_every is not null)
);
create index on one_offs (user_id);
create index on one_offs (account_id);

-- Transactions in a one-off's account that are money in for it, or paid out of it.
create table one_off_transactions (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  one_off_id integer not null references one_offs (id) on delete cascade,
  transaction_id integer not null references transactions (id) on delete cascade,
  created_at timestamptz not null default now(),
  -- a transaction counts towards one one-off at most
  primary key (user_id, transaction_id)
);
create index on one_off_transactions (one_off_id);

alter table one_offs enable row level security;
create policy "household rows" on one_offs for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));

alter table one_off_transactions enable row level security;
create policy "household rows" on one_off_transactions for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));
