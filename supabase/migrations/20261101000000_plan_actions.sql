-- Plan action items: things to do about the plan, ticked off as they're done. They belong
-- to the household, not to one plan, so they survive a rebuild.

create table plan_actions (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  title text not null,
  detail text,
  due_date date,
  -- the plan's focus item it came from, when it did
  focus_title text,
  created_by text not null default 'website' check (created_by in ('website', 'mcp')),
  done_at timestamptz,
  created_at timestamptz not null default now()
);

alter table plan_actions enable row level security;
create policy "household rows" on plan_actions for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));
