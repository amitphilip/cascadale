-- Cas's memory: what the advisor agent (lib/cas) has noticed, what you decided,
-- and what's still to do, so it picks up where it left off in the next conversation.

create table cas_notes (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  -- 'observation' (something it noticed), 'decision' (something you chose),
  -- 'preference' (how you want things done) or 'todo' (an action still open)
  kind text not null check (kind in ('observation', 'decision', 'preference', 'todo')),
  content text not null,
  -- for a todo: when it should be done by, if it has a date
  due_date date,
  created_at timestamptz not null default now(),
  -- set when a todo is done or a note no longer holds; resolved notes are kept as history
  resolved_at timestamptz,
  resolution text
);
create index cas_notes_open_idx on cas_notes (resolved_at, id desc);

alter table cas_notes enable row level security;
create policy "own rows" on cas_notes for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create index on cas_notes (user_id);
