-- Proactive Cas, and what it needs to give better advice.
--
-- * accounts.interest_rate: the annual rate on an account (debt or savings), so Cas can weigh
--   paying down debt against saving.
-- * plan_items.from_account_id: the account an allocation's money leaves from (usually where
--   the pay lands), so a pay landing can say what to move.
-- * cas_nudges: messages Cas sends without being asked (a pay landed, the Monday check-in).
--   They show in the Home inbox and are pushed to the household's devices.
-- * push_subscriptions: each device that asked for Cas's messages (Web Push).

alter table accounts add column interest_rate numeric(6, 3)
  check (interest_rate is null or (interest_rate >= 0 and interest_rate <= 100));
comment on column accounts.interest_rate is 'Annual interest rate in percent, e.g. 8.95; null when unknown';

alter table plan_items add column from_account_id integer references accounts (id) on delete set null;

create table cas_nudges (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  kind text not null check (kind in ('payday', 'weekly')),
  title text not null,
  body text not null,
  -- one nudge per event, e.g. 'payday:<transaction id>' or 'weekly:<monday>'
  dedupe_key text not null,
  due_date date,
  created_at timestamptz not null default now(),
  pushed_at timestamptz,
  done_at timestamptz,
  unique (user_id, dedupe_key)
);
create index on cas_nudges (user_id, done_at);

alter table cas_nudges enable row level security;
create policy "household rows" on cas_nudges for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));

create table push_subscriptions (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  -- the person whose device it is (a household member signs in as themselves)
  member_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);
create index on push_subscriptions (user_id);

alter table push_subscriptions enable row level security;
create policy "household rows" on push_subscriptions for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));

-- category_spend for one user, for the akahu-sync edge function: it acts with the service
-- role, which row level security doesn't scope, so this names the user itself. Only the
-- service role may call it.
create function category_spend_of(p_user uuid, p_start date, p_end date)
returns table (id integer, name text, budget numeric, spent numeric)
language sql stable as $$
  select c.id, c.name, c.monthly_budget, -sum(t.amount) as spent
  from transactions t
  left join categories c on c.id = t.category_id
  where t.user_id = p_user
    and t.date >= p_start and t.date < p_end
    and (c.kind = 'expense' or (c.id is null and t.amount < 0))
    and not exists (
      select 1 from pot_entries e join plan_pots p on p.id = e.pot_id
      where e.transaction_id = t.id and e.kind = 'draw'
        and p.type = 'sinking_fund' and not p.removed
    )
    and not exists (select 1 from one_off_transactions o where o.transaction_id = t.id)
  group by c.id, c.name, c.monthly_budget
  order by spent desc
$$;
revoke execute on function category_spend_of(uuid, date, date) from public, anon, authenticated;
grant execute on function category_spend_of(uuid, date, date) to service_role;
