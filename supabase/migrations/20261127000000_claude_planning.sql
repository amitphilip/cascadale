-- Claude plans; Cascadale keeps the data, the rules and the figures.
--
-- Cas, the in-app agent, is switched off (CAS_ENABLED, lib/flags.ts). The plan and the
-- short-term allocations it made stay as they are and become plain data that Claude edits
-- through the MCP tools (lib/planning), each change logged with who asked, who made it, why,
-- and the values before and after. Long-term plan changes wait as pending changes until a
-- member approves them.

-- ── Who made it ──────────────────────────────────────────────────────────────
-- website / mcp: Cas made the whole plan; claude: Claude through the plan tools; you: in the app.
alter table plans drop constraint plans_made_by_check;
alter table plans add constraint plans_made_by_check
  check (made_by in ('website', 'mcp', 'claude', 'you'));
-- A plan Claude keeps item by item has no overall verdict.
alter table plans alter column verdict drop not null;
alter table plans alter column verdict_note drop not null;

alter table short_term_allocations drop constraint short_term_allocations_made_by_check;
alter table short_term_allocations add constraint short_term_allocations_made_by_check
  check (made_by in ('cas', 'claude', 'you'));

-- ── Plan items ───────────────────────────────────────────────────────────────
alter table plan_items drop constraint plan_items_purpose_check;
alter table plan_items add constraint plan_items_purpose_check
  check (purpose in ('bills', 'budget', 'one_off', 'savings', 'goal', 'buffer', 'debt'));

alter table plan_items
  -- whose pay it comes from; null when shared or not from a pay
  add column from_member_id uuid references auth.users (id) on delete set null,
  add column start_date date,
  add column end_date date,
  -- for a savings goal, debt or one-off: the amount it works towards
  add column target numeric(14, 2) check (target is null or target >= 0),
  add column notes text,
  -- what pays it, for plan_vs_actual: merchant keys, or "to:<account id>" for a transfer
  add column match_keys text[] not null default '{}',
  -- soft delete: removed items keep their history
  add column removed_at timestamptz,
  add column updated_at timestamptz not null default now();

-- The plan's allocations already say which account each leaves from: the holder of that
-- account is whose pay it comes from.
update plan_items i
set from_member_id = a.holder_id
from accounts a
where a.id = i.from_account_id and i.from_member_id is null and a.holder_id is not null;

-- ── Notes ────────────────────────────────────────────────────────────────────
-- A decision about who pays for something, in a form the plan can be checked against:
-- "Mary pays the school fees" is subject 'school fees', payer Mary.
alter table cas_notes
  add column subject text,
  add column payer_member_id uuid references auth.users (id) on delete set null;

-- ── Accounts ─────────────────────────────────────────────────────────────────
-- What each account is for ("Cabin - Cabin King payments"), and whether its money is free to
-- spend (null: judged from its type).
alter table accounts
  add column purpose text,
  add column spendable boolean;

-- ── Change log ───────────────────────────────────────────────────────────────
-- Every change to the plan, the short-term allocations and committed purchases.
create table plan_changes (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  -- plan_item, short_term, purchase or pending (a pending change decided)
  entity text not null check (entity in ('plan_item', 'short_term', 'purchase', 'pending')),
  -- the plan item, short-term allocation, one-off or pending change it's about
  entity_id integer,
  action text not null check (action in ('create', 'update', 'remove', 'set', 'commit', 'approve', 'reject', 'propose')),
  -- the member who asked for it
  asked_by uuid references auth.users (id) on delete set null,
  -- claude: Claude through the MCP tools; you: a person in the app
  made_by text not null check (made_by in ('claude', 'you')),
  reason text not null check (length(trim(reason)) > 0),
  before jsonb,
  after jsonb,
  created_at timestamptz not null default now()
);
create index on plan_changes (user_id, created_at desc);
create index on plan_changes (entity, entity_id);

alter table plan_changes enable row level security;
create policy "household rows" on plan_changes for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));

-- ── Pending plan changes ─────────────────────────────────────────────────────
-- Long-term plan edits waiting for a member's approval. A change to a shared item (a joint
-- account, the mortgage, daycare) takes either member; a personal one takes its owner.
create table pending_plan_changes (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  -- upsert: add or change an item (plan_item_id null to add); remove: soft-delete one
  kind text not null check (kind in ('upsert', 'remove')),
  plan_item_id integer references plan_items (id) on delete cascade,
  -- the item's fields as they'd be (upsert)
  payload jsonb not null default '{}',
  -- the item as it was when proposed, to show what moves
  before jsonb,
  reason text not null check (length(trim(reason)) > 0),
  asked_by uuid references auth.users (id) on delete set null,
  made_by text not null check (made_by in ('claude', 'you')),
  -- needs either member's approval (shared) or only approver_id's
  shared boolean not null,
  approver_id uuid references auth.users (id) on delete set null,
  -- set when a commit_purchase made it
  purchase text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  decided_by uuid references auth.users (id) on delete set null,
  decided_at timestamptz,
  decision_reason text,
  created_at timestamptz not null default now()
);
create index on pending_plan_changes (user_id, status, id desc);

alter table pending_plan_changes enable row level security;
create policy "household rows" on pending_plan_changes for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));
