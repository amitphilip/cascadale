-- Corrections waiting for Cas, and the month's spending line by line for Home.
--
-- * cas_queue: moving a transaction from Home's budget tracking (to another category, or to
--   count towards a one-off payment) applies straight away, so the numbers are right at once,
--   and queues the change here for Cas. Cas takes the queue in once a day (the first bank sync
--   from 6am) or when someone presses Update Cas: a move marked `remember` becomes the
--   merchant's rule, so later transactions follow it; the rest stay one-time exceptions.
--   Each row keeps what Cas did with it (outcome), so the briefing can say what was corrected.
-- * spend_transactions: every transaction that counts as money in or out over a period, with
--   the one-off payment it counts towards. The same rows category_spend adds up (sinking-fund
--   draws out, transfers out), so Home's breakdown sums to the budget figures.

create table cas_queue (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  transaction_id integer not null references transactions (id) on delete cascade,
  description text not null,
  -- the merchant the rule would be for (lib/rules.ts merchantKey), worked out when queued
  merchant_key text not null,
  amount numeric(14, 2) not null,
  tx_date date not null,
  from_category_id integer references categories (id) on delete set null,
  from_one_off_id integer references one_offs (id) on delete set null,
  -- where it went: a category, a one-off payment, or neither (back to uncategorized)
  to_category_id integer references categories (id) on delete set null,
  to_one_off_id integer references one_offs (id) on delete set null,
  -- make it the merchant's rule, not just this transaction
  remember boolean not null default false,
  moved_by uuid default auth.uid() references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  processed_at timestamptz,
  outcome text,
  check (to_category_id is null or to_one_off_id is null)
);
-- one change per transaction waits at a time: moving it again replaces the waiting one
create unique index cas_queue_pending_idx on cas_queue (user_id, transaction_id) where processed_at is null;
create index on cas_queue (user_id, processed_at);

alter table cas_queue enable row level security;
create policy "household rows" on cas_queue for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));

create function spend_transactions(p_start date, p_end date)
returns table (
  id integer,
  date date,
  description text,
  amount numeric,
  account_id integer,
  category_id integer,
  category_source text,
  one_off_id integer
)
language sql stable as $$
  select t.id, t.date, t.description, t.amount, t.account_id, t.category_id, t.category_source,
    o.one_off_id
  from transactions t
  left join categories c on c.id = t.category_id
  left join one_off_transactions o on o.transaction_id = t.id
  where t.date >= p_start and t.date < p_end
    and coalesce(c.kind, '') <> 'transfer'
    and not exists (
      select 1 from pot_entries e join plan_pots p on p.id = e.pot_id
      where e.transaction_id = t.id and e.kind = 'draw'
        and p.type = 'sinking_fund' and not p.removed
    )
  order by t.date desc, t.id desc
$$;
revoke execute on function spend_transactions(date, date) from public, anon;
grant execute on function spend_transactions(date, date) to authenticated;
