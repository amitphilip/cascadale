-- Changes Cas proposes instead of describing them: a tool call (name and arguments) with its
-- reason, waiting for a person to approve or reject it. Approving runs the call through the
-- shared layer as actor 'user', and the change it records links back here.

create table cas_proposals (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  tool text not null,
  args jsonb not null default '{}',
  reason text not null,
  -- cas: from a background run; system: a transaction that might finish an action item
  source text not null default 'cas' check (source in ('cas', 'system')),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'superseded', 'failed')),
  -- the latest change and sync the proposal was made on; a newer one can make it stale
  based_on_change_id integer references plan_changes (id) on delete set null,
  based_on_sync_at timestamptz,
  created_at timestamptz not null default now(),
  decided_at timestamptz,
  -- who approved or rejected it (set from the session, see below)
  decided_by uuid references auth.users (id) on delete set null,
  decision_reason text,
  -- the change approving it recorded, what it returned, or why it failed
  change_id integer references plan_changes (id) on delete set null,
  result jsonb,
  error text
);
create index cas_proposals_status_idx on cas_proposals (user_id, status, id desc);

alter table cas_proposals enable row level security;
create policy "household rows" on cas_proposals for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));

-- Whoever settles a proposal is the signed-in user; it isn't taken from the request.
create function cas_proposals_decided()
returns trigger
language plpgsql
as $$
begin
  if new.status <> old.status and new.status in ('approved', 'rejected', 'failed') then
    new.decided_at := coalesce(new.decided_at, now());
    new.decided_by := auth.uid();
  end if;
  return new;
end;
$$;

create trigger cas_proposals_decided
before update on cas_proposals
for each row execute function cas_proposals_decided();

alter table plan_changes
  add column proposal_id integer references cas_proposals (id) on delete set null;
