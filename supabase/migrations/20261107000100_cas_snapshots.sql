-- Cas's "state of play": written by its background worker (lib/cas/worker.ts) after each
-- sync and plan change, read by get_status without running a model. Every run adds a row,
-- so the history is kept; the latest is the household's highest id.

create table cas_snapshots (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  status text not null check (status in ('on_track', 'watch', 'off_track')),
  headline text not null,
  -- forecast less target on the goal's end date: below zero is short
  goal_gap numeric(14, 2),
  low_point_date date,
  low_point_amount numeric(14, 2),
  -- [{ title, detail, actionId, dueDate }], actionId linking to plan_actions
  top_actions jsonb not null default '[]',
  -- [{ kind: drift | stale_feed | uncategorised | overdraft | series | other, message }]
  warnings jsonb not null default '[]',
  -- the proposals this run made or kept (see cas_proposals)
  proposals jsonb not null default '[]',
  -- every figure the snapshot was built from (lib/plan-figures.ts)
  figures jsonb,
  -- the latest finished sync and recorded change this snapshot reflects
  based_on_sync_at timestamptz,
  based_on_sync_run_id uuid,
  based_on_change_id integer references plan_changes (id) on delete set null,
  -- the model that judged it (null when it couldn't run and the figures speak alone)
  model text,
  escalation_reason text,
  input_tokens integer,
  output_tokens integer,
  latency_ms integer,
  -- what went wrong with the model, when something did
  error text,
  created_at timestamptz not null default now()
);
create index cas_snapshots_latest_idx on cas_snapshots (user_id, id desc);

alter table cas_snapshots enable row level security;
create policy "household rows" on cas_snapshots for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));
