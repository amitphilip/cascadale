-- Cascadale: schema, default categories, statement storage and query functions.
--
-- The app connects with the publishable key as the signed-in user. Every row belongs to
-- a user (user_id defaults to auth.uid()) and row level security limits each user to
-- their own rows, so queries don't filter by user themselves.

-- ── Tables ─────────────────────────────────────────────────────────────────

create table accounts (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  name text not null,
  type text not null default 'checking',
  institution text,
  opening_balance numeric(14, 2) not null default 0,
  archived boolean not null default false,
  created_at timestamptz not null default now()
);

create table categories (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  name text not null,
  kind text not null default 'expense',
  monthly_budget numeric(14, 2),
  unique (user_id, name)
);

-- One uploaded statement file. The raw file lives in the "statements" storage bucket.
create table statements (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  account_id integer not null references accounts (id) on delete cascade,
  file_name text not null,
  stored_name text not null,
  row_count integer not null default 0,
  inserted_count integer not null default 0,
  period_start date,
  period_end date,
  imported_at timestamptz not null default now()
);

-- "contains": case-insensitive substring of the description.
-- "merchant": pattern is a normalized merchant key (see lib/rules.ts), also matched fuzzily.
create table rules (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  pattern text not null,
  category_id integer not null references categories (id) on delete cascade,
  kind text not null default 'contains',
  source text not null default 'manual',
  confidence integer not null default 100,
  note text,
  reason text,
  created_at timestamptz not null default now()
);
create index rules_kind_pattern_idx on rules (kind, pattern);

create table transactions (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  account_id integer not null references accounts (id) on delete cascade,
  statement_id integer references statements (id) on delete cascade,
  date date not null,
  description text not null,
  -- signed: negative is money out, positive is money in
  amount numeric(14, 2) not null,
  category_id integer references categories (id) on delete set null,
  rule_id integer references rules (id) on delete set null,
  category_source text,
  category_confidence integer,
  notes text,
  source text not null,
  -- dedupe key for imported rows; null for manual entries
  hash text,
  created_at timestamptz not null default now()
);
create unique index transactions_account_hash_idx on transactions (account_id, hash);
create index transactions_date_idx on transactions (date);
create index transactions_category_idx on transactions (category_id);
create index transactions_rule_idx on transactions (rule_id);

create table settings (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  key text not null,
  value text not null,
  primary key (user_id, key)
);

create table recurring_overrides (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  key text not null,
  basis text,
  growth_rate numeric(8, 4),
  amount numeric(14, 2),
  excluded boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key (user_id, key)
);

create table category_projections (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  category_id integer primary key references categories (id) on delete cascade,
  basis text,
  growth_rate numeric(8, 4),
  amount numeric(14, 2),
  updated_at timestamptz not null default now()
);

create table plan_threads (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  snapshot jsonb not null,
  created_at timestamptz not null default now()
);

create table plan_messages (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  thread_id integer not null references plan_threads (id) on delete cascade,
  role text not null,
  content text not null,
  context text,
  plan jsonb,
  created_at timestamptz not null default now()
);
create index plan_messages_thread_idx on plan_messages (thread_id);

create table upcoming_expenses (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  name text not null,
  amount numeric(14, 2) not null,
  due_date date not null,
  account_id integer references accounts (id) on delete set null,
  note text,
  created_at timestamptz not null default now()
);
create index upcoming_expenses_due_idx on upcoming_expenses (due_date);

create table check_ins (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  period_start date not null,
  period_end date not null,
  stats jsonb not null,
  result jsonb not null,
  created_at timestamptz not null default now()
);

-- Each user sees and changes only their own rows.
do $$
declare
  t text;
begin
  foreach t in array array[
    'accounts', 'categories', 'statements', 'rules', 'transactions', 'settings',
    'recurring_overrides', 'category_projections', 'plan_threads', 'plan_messages',
    'upcoming_expenses', 'check_ins'
  ] loop
    execute format('alter table %I enable row level security', t);
    execute format(
      'create policy "own rows" on %I for all to authenticated '
      'using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))', t);
    execute format('create index on %I (user_id)', t);
  end loop;
end;
$$;

