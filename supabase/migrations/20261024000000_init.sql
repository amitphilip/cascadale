-- ── Query functions (called with .rpc from lib/queries.ts and app/actions.ts) ──
-- They run as the caller, so row level security scopes them to the signed-in user.
-- Functions that can return many rows return one jsonb array, which isn't subject to
-- the API's row limit.

create function accounts_with_balances()
returns table (
  id integer, name text, type text, institution text, opening_balance numeric,
  archived boolean, tx_total numeric, tx_count integer, last_date text
)
language sql stable as $$
  select a.id, a.name, a.type, a.institution, a.opening_balance, a.archived,
    coalesce(sum(t.amount), 0), count(t.id)::int, max(t.date)::text
  from accounts a
  left join transactions t on t.account_id = a.id
  group by a.id
  order by a.archived, a.name
$$;

create function categories_with_usage()
returns table (id integer, name text, kind text, monthly_budget numeric, tx_count integer)
language sql stable as $$
  select c.id, c.name, c.kind, c.monthly_budget, count(t.id)::int
  from categories c
  left join transactions t on t.category_id = c.id
  group by c.id
  order by c.kind, c.name
$$;

-- Every rule with how many transactions it categorized, busiest first.
create function rule_tags()
returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(x order by x."txCount" desc, x.pattern, x.id), '[]')
  from (
    select r.id, r.pattern, r.kind, r.source, r.category_id as "categoryId",
      count(t.id)::int as "txCount"
    from rules r
    left join transactions t on t.rule_id = r.id
    group by r.id
  ) x
$$;

-- One row per rule that has auto-categorized at least one transaction, with the
-- average confidence of those transactions. p_like is an ilike pattern, or null.
create function rule_review(p_like text)
returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(x order by x.confidence asc nulls last, x.tx_count desc, x.id), '[]')
  from (
    select r.id, r.pattern, r.kind, r.source, r.confidence as rule_confidence, r.note, r.reason,
      r.category_id,
      count(t.id)::int as tx_count,
      count(t.id) filter (where t.category_source <> 'manual')::int as auto_count,
      coalesce(sum(t.amount), 0) as total,
      round(avg(t.category_confidence) filter (where t.category_source <> 'manual'))::int
        as confidence,
      min(t.description) as example
    from rules r
    join transactions t on t.rule_id = r.id
    group by r.id
    having count(t.id) filter (where t.category_source <> 'manual') > 0
      and (p_like is null
        or r.pattern ilike p_like or r.note ilike p_like or r.reason ilike p_like
        or bool_or(t.description ilike p_like))
  ) x
$$;

-- Counts of transactions by how they were categorized.
create function categorization_stats(p_low integer)
returns table (
  total integer, uncategorized integer, manual integer, rule integer, ai integer, low integer
)
language sql stable as $$
  select count(*)::int,
    count(*) filter (where category_id is null)::int,
    count(*) filter (where category_source = 'manual' and category_id is not null)::int,
    count(*) filter (where category_source = 'rule')::int,
    count(*) filter (where category_source = 'ai')::int,
    count(*) filter (where category_source <> 'manual' and category_confidence < p_low)::int
  from transactions
$$;

-- Count and money in/out for the transactions page filters; null arguments don't filter.
create function transaction_totals(
  p_account integer, p_category integer, p_uncategorized boolean, p_rule integer,
  p_start date, p_end date, p_q text
)
returns table (count integer, inflow numeric, outflow numeric)
language sql stable as $$
  select count(*)::int,
    coalesce(sum(amount) filter (where amount > 0), 0),
    coalesce(sum(amount) filter (where amount < 0), 0)
  from transactions
  where (p_account is null or account_id = p_account)
    and (p_category is null or category_id = p_category)
    and (not coalesce(p_uncategorized, false) or category_id is null)
    and (p_rule is null or rule_id = p_rule)
    and (p_start is null or date >= p_start)
    and (p_end is null or date < p_end)
    and (p_q is null or description ilike '%' || p_q || '%')
$$;

create function transaction_months()
returns setof text
language sql stable as $$
  select distinct to_char(date, 'YYYY-MM') from transactions order by 1 desc
$$;

-- Income and spending per month in [p_start, p_end), transfers excluded.
create function monthly_cashflow(p_start date, p_end date)
returns table (month text, income numeric, expense numeric)
language sql stable as $$
  select to_char(t.date, 'YYYY-MM'),
    coalesce(sum(t.amount) filter (where t.amount > 0), 0),
    coalesce(-sum(t.amount) filter (where t.amount < 0), 0)
  from transactions t
  left join categories c on c.id = t.category_id
  where coalesce(c.kind, '') <> 'transfer'
    and t.date >= p_start and t.date < p_end
  group by 1
$$;

-- Net spending per expense category in [p_start, p_end) (refunds reduce spend).
create function category_spend(p_start date, p_end date)
returns table (id integer, name text, budget numeric, spent numeric)
language sql stable as $$
  select c.id, c.name, c.monthly_budget, -sum(t.amount) as spent
  from transactions t
  left join categories c on c.id = t.category_id
  where t.date >= p_start and t.date < p_end
    and (c.kind = 'expense' or (c.id is null and t.amount < 0))
  group by c.id, c.name, c.monthly_budget
  order by spent desc
$$;

-- Up to p_months months ending with the latest transaction, starting no earlier than
-- the first one: [start_date, end_date), its last day and length.
create function average_window(p_months integer)
returns table (start_date text, end_date text, last_date text, days integer)
language sql stable as $$
  with b as (
    select greatest(min(date), (max(date) + 1 - make_interval(months => p_months))::date) as s,
      max(date) + 1 as e
    from transactions
  )
  select s::text, e::text, (e - 1)::text, e - s from b
$$;

-- Net per category for a month and for the averaging window; transfers excluded,
-- uncategorized money in/out reported as its own income/expense line.
create function income_statement(p_start date, p_end date, p_wstart date, p_wend date)
returns table (id integer, name text, kind text, month_total numeric, window_total numeric)
language sql stable as $$
  select c.id, c.name,
    case when c.id is null then (case when t.amount > 0 then 'income' else 'expense' end)
      else c.kind end,
    coalesce(sum(t.amount) filter (where t.date >= p_start and t.date < p_end), 0),
    coalesce(sum(t.amount) filter (where t.date >= p_wstart and t.date < p_wend), 0)
  from transactions t
  left join categories c on c.id = t.category_id
  where coalesce(c.kind, '') <> 'transfer'
    and ((t.date >= p_start and t.date < p_end) or (t.date >= p_wstart and t.date < p_wend))
  group by 1, 2, 3
$$;

-- Active accounts with transaction sums before p_end, before the window, within it, and
-- weighted by the days each one counts toward the window's closing balances.
create function balances_as_of(p_end date, p_wstart date, p_wend date)
returns table (
  id integer, name text, type text, opening numeric, end_total numeric,
  start_total numeric, window_total numeric, weighted numeric
)
language sql stable as $$
  select a.id, a.name, a.type, a.opening_balance,
    coalesce(sum(t.amount) filter (where t.date < p_end), 0),
    coalesce(sum(t.amount) filter (where t.date < p_wstart), 0),
    coalesce(sum(t.amount) filter (where t.date >= p_wstart and t.date < p_wend), 0),
    -- each transaction counts toward every remaining day's closing balance
    coalesce(sum(t.amount * (p_wend - t.date))
      filter (where t.date >= p_wstart and t.date < p_wend), 0)
  from accounts a
  left join transactions t on t.account_id = a.id
  where not a.archived
  group by a.id
  order by a.name
$$;

-- Non-transfer transactions in [p_start, p_end) with the rule that categorized each.
create function recurring_transactions(p_start date, p_end date)
returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(to_jsonb(x) - 'id' order by x.date, x.id), '[]')
  from (
    select t.id, t.date::text as date, t.account_id as "accountId", t.description, t.amount,
      t.category_id as "categoryId", c.kind as "categoryKind",
      t.rule_id as "ruleId", r.note as "ruleNote"
    from transactions t
    left join categories c on c.id = t.category_id
    left join rules r on r.id = t.rule_id
    where coalesce(c.kind, '') <> 'transfer'
      and t.date >= p_start and t.date < p_end
  ) x
$$;

-- Non-transfer transactions logged after p_since, or when it's null, in the last
-- p_recent_days days of data.
create function checkin_transactions(p_since timestamptz, p_recent_days integer)
returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(to_jsonb(x) - 'id' order by x.date, x.id), '[]')
  from (
    select t.id, t.date::text as date, t.description, t.amount, t.account_id as "accountId",
      c.name as "categoryName", c.kind as "categoryKind"
    from transactions t
    left join categories c on c.id = t.category_id
    where coalesce(c.kind, '') <> 'transfer'
      and case when p_since is not null then t.created_at > p_since
        else t.date > (select max(date) from transactions) - p_recent_days end
  ) x
$$;

-- Categorize the given transactions that are still uncategorized; returns how many changed.
create function set_transaction_categories(
  p_ids integer[], p_category_id integer, p_rule_id integer, p_source text,
  p_confidence integer
)
returns integer
language plpgsql as $$
declare
  n integer;
begin
  update transactions
  set category_id = p_category_id, rule_id = p_rule_id, category_source = p_source,
    category_confidence = p_confidence
  where id = any (p_ids) and category_id is null;
  get diagnostics n = row_count;
  return n;
end;
$$;

-- Record a statement and insert its rows in one transaction, skipping rows already
-- imported (same account and hash). The statement is dropped if nothing was new.
create function import_statement(p_statement jsonb, p_rows jsonb)
returns table (inserted integer, categorized integer)
language plpgsql as $$
declare
  v_id integer;
  v_inserted integer;
  v_categorized integer;
begin
  insert into statements (account_id, file_name, stored_name, row_count, period_start, period_end)
  values (
    (p_statement ->> 'account_id')::integer,
    p_statement ->> 'file_name',
    p_statement ->> 'stored_name',
    (p_statement ->> 'row_count')::integer,
    (p_statement ->> 'period_start')::date,
    (p_statement ->> 'period_end')::date
  )
  returning statements.id into v_id;

  with ins as (
    insert into transactions (
      account_id, statement_id, date, description, amount, category_id, rule_id,
      category_source, category_confidence, source, hash
    )
    select r.account_id, v_id, r.date, r.description, r.amount, r.category_id, r.rule_id,
      r.category_source, r.category_confidence, 'import', r.hash
    from jsonb_to_recordset(p_rows) as r (
      account_id integer, date date, description text, amount numeric, category_id integer,
      rule_id integer, category_source text, category_confidence integer, hash text
    )
    on conflict (account_id, hash) do nothing
    returning transactions.category_id
  )
  select count(*)::integer, count(ins.category_id)::integer into v_inserted, v_categorized
  from ins;

  if v_inserted = 0 then
    delete from statements where statements.id = v_id;
  else
    update statements set inserted_count = v_inserted where statements.id = v_id;
  end if;
  return query select v_inserted, v_categorized;
end;
$$;

-- Set monthly budgets on expense categories; an amount of 0 clears the budget.
create function set_category_budgets(p_budgets jsonb)
returns void
language sql as $$
  update categories c
  set monthly_budget = case when b.amount = 0 then null else round(b.amount) end
  from jsonb_to_recordset(p_budgets) as b (category_id integer, amount numeric)
  where c.id = b.category_id and c.kind = 'expense'
$$;

