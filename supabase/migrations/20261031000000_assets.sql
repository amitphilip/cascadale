-- Assets: things you own that no bank feed values, such as the house or a car. Their
-- value is whatever you last entered; net worth adds them to your account balances.

create table assets (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  name text not null,
  kind text not null default 'other',
  value numeric(14, 2) not null,
  valued_on date not null default current_date,
  note text,
  created_at timestamptz not null default now()
);

alter table assets enable row level security;
create policy "household rows" on assets for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));
