-- Cas's short-term allocation: the transfers for one person's pay this pay cycle.
--
-- The plan (plans, plan_items) is the long-term allocation: what each pay does, made now and
-- then. Each pay cycle Cas also works out the concrete moves for this pay: "move this much
-- from here to there". A line either sets a plan allocation's amount for this pay (it's late,
-- short, or not needed) or is a move the plan doesn't name (paying off the card, topping up
-- savings). Cas looks again whenever a sync brings in something new for that person's
-- accounts (fingerprint), and anyone can change a line by talking to Cas in Claude.
--
-- lines: [{ id, planItemId, title, fromAccountId, toAccountId, match, amount, dueDate,
--           reason, by }]
--   planItemId: the plan allocation it sets this pay's amount for, or null
--   toAccountId: one of the household's accounts; null when the money leaves the household,
--     then match is the merchant key (lib/rules.ts merchantKey) its transactions carry
--   by: 'cas' or 'you' (set through Claude); Cas keeps 'you' lines when it looks again

create table short_term_allocations (
  user_id uuid not null default public.data_owner() references auth.users (id) on delete cascade,
  id integer generated by default as identity primary key,
  -- whose pay it is
  member_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  -- the pay cycle: from the payday that began it to the next (lib/my-allocation.ts payCycle)
  cycle_start date not null,
  cycle_end date not null,
  lines jsonb not null default '[]',
  -- Cas's read of this pay in a sentence or two
  summary text,
  -- what the lines were worked out from; when the data's differs, Cas looks again
  fingerprint text not null,
  -- cas: Cas worked it out; you: last changed through Claude
  made_by text not null default 'cas' check (made_by in ('cas', 'you')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, member_id, cycle_start)
);

alter table short_term_allocations enable row level security;
create policy "household rows" on short_term_allocations for all to authenticated
  using (user_id = (select public.data_owner()))
  with check (user_id = (select public.data_owner()));
